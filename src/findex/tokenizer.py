"""Потоковий токенізатор.

Правила (їх же перевіряють тести):

1. Текст нормалізується в Unicode NFC, потім casefold() (а не lower(): "Straße" -> "strasse"),
   потім ще раз NFC, бо casefold може розкласти символ.
2. Токен - послідовність букв і цифр будь-якого алфавіту (\\w без підкреслення).
   Підкреслення розділяє слова, бо в Gutenberg ним позначають курсив: _word_.
3. Апостроф всередині слова лишається в токені: don't, м'ясо, l'amour.
   Типографський ’ та модифікатор ʼ (український апостроф) приводяться до звичайного '.
   Апострофи на краях слова (лапки, 'hello', dogs') відкидаються.
4. Дефіс між двома буквено-цифровими шматками лишається: well-known, 2020-2021.
   Unicode-дефіси (U+2010, U+2011) приводяться до '-'. Тире (—, –) та "--" розділяють слова.
5. Цифри - звичайні символи слова: covid19, 1984, b2b. Але розділювачі розрядів і десяткові
   крапки не склеюють число: "3.14" -> "3", "14"; "1,000" -> "1", "000".
6. Одиночні знаки пунктуації й пробіли токенами не є.

Відомі обмеження: комбіновані символи, для яких нема попередньо складеної форми
(наприклад, "i" + U+0307 після casefold турецької "İ"), не входять в \\w і розбивають слово.
"""

import re
import unicodedata
from collections.abc import Iterator

# ʼ (U+02BC) для regex це буква (\w), тож з основного класу її треба виключити: інакше
# самотній ʼ ставав токеном "'" (це знайшов Hypothesis). Всередині слова вона апостроф.
_TOKEN = re.compile(r"[^\W_ʼ]+(?:['’ʼ\-‐‑][^\W_ʼ]+)*")

# все, що вважаємо апострофом або дефісом, приводимо до ASCII-варіанту
_UNIFY = str.maketrans({"’": "'", "ʼ": "'", "‐": "-", "‑": "-"})


def normalize(text: str) -> str:
    text = unicodedata.normalize("NFC", text)
    text = text.casefold()
    return unicodedata.normalize("NFC", text)


def tokenize(text: str) -> Iterator[str]:
    """Віддає токени з тексту по одному (генератор, нічого не збирає в список)."""
    for match in _TOKEN.finditer(normalize(text)):
        yield match.group().translate(_UNIFY)


def term_of(word: str) -> str:
    """Приводить одне слово з тексту до вигляду терма (так само, як tokenize)."""
    return normalize(word).translate(_UNIFY)
